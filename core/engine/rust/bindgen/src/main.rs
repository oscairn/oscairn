// Generates core/engine/rust/src/bindings.rs from core/engine/src/engine_core.h and core/plugin-host/src/worker_shared.h,
// and core/clap-host/rust/src/bindings.rs from core/plugin-host/src/clap_host.h and kick_clap/bridge.h, on a machine with libclang:
//   LIBCLANG_PATH=<its folder> cargo run --manifest-path core/engine/rust/bindgen/Cargo.toml -- <repo root>
// The output is checked in; each crate's test (engine_core_h_unchanged, clap_host_h_unchanged) fails when its headers move under it.
fn main() {
    let root = std::env::args().nth(1).expect("the repo root");
    let fnv = |p: &str| std::fs::read(p).expect("header").iter().fold(0xcbf29ce484222325u64, |h, &b| (h ^ u64::from(b)).wrapping_mul(0x100000001b3));
    let builder = || {
        bindgen::Builder::default()
            .clang_arg(format!("-I{root}/core/clap-ext/include"))
            .clang_arg(format!("-I{root}/core/clap-host/third_party/clap/include"))
            .clang_arg(format!("-I{root}/core/clap-host/include"))
            .derive_default(false)
            .derive_debug(false)
            .derive_partialeq(true)
            .layout_tests(true)
            .use_core()
            .formatter(bindgen::Formatter::Rustfmt)
    };
    let allow = "#![allow(non_camel_case_types, non_snake_case, dead_code, clippy::all, clippy::undocumented_unsafe_blocks, unpredictable_function_pointer_comparisons)]\n";

    let header = format!("{root}/core/engine/src/engine_core.h");
    let worker = format!("{root}/core/plugin-host/src/worker_shared.h"); // the engine-worker shared block
    // Types the crate defines itself (methods, atomics, safety), with the same layout.
    let own = [
        ("oscairn_event", "crate::event::Event"),
        ("oscairn_zones", "crate::route::Zones"),
        ("oscairn_activity", "crate::budget::Activity"),
        ("oscairn_key", "crate::notes::Key"),
        ("oscairn_block", "crate::notes::Timing"),
        ("oscairn_voice_budget_note_t", "crate::notes::VoiceNote"),
        ("oscairn_bus", "crate::audio::Bus"),
        ("oscairn_peaks", "crate::audio::Peaks"),
        ("oscairn_route", "crate::route::NoteRoute"),
        ("oscairn_notes", "crate::notes::Notes"),
        ("oscairn_audio", "crate::audio::Audio"),
        ("oscairn_run", "crate::run::Run"),
        ("oscairn_harmony", "crate::run::Harmony"),
        ("oscairn_atomic_u32", "core::sync::atomic::AtomicU32"),
        ("oscairn_atomic_u64", "core::sync::atomic::AtomicU64"),
        ("oscairn_atomic_f64", "core::sync::atomic::AtomicU64"), // a double's bits
        ("oscairn_worker_event", "crate::event::Event"),
    ];
    let unused = ["oscairn_voice_budget_note", "oscairn_zone"]; // behind types the crate defines
    let mut b = builder().blocklist_function(".*").header(&header).header(&worker).allowlist_file(&header).allowlist_file(&worker).allowlist_type("oscairn_voice_budget_context_t");
    for c in own.iter().map(|o| o.0).chain(unused) {
        b = b.blocklist_type(c);
    }
    let mut out = String::from("// Generated by bindgen 0.72.1 from core/engine/src/engine_core.h by core/engine/rust/bindgen; regenerate\n// after changing it or voice-budget.h (the test engine_core_h_unchanged says when). Do not edit.\n");
    out += allow;
    for (c, r) in own {
        out += &format!("pub type {c} = {r};\n");
    }
    // What the bindings were made from, so a test notices engine_core.h or voice-budget.h changing under them.
    out += &format!("pub const MADE_FROM: [u64; 3] = [{:#x}, {:#x}, {:#x}];\n", fnv(&header), fnv(&format!("{root}/core/clap-ext/include/oscairn-clap/voice-budget.h")), fnv(&worker));
    out += &b.generate().expect("bindgen").to_string();
    std::fs::write(format!("{root}/core/engine/rust/src/bindings.rs"), out).expect("write");

    // The CLAP host's C interface, and what it reaches in kick_clap (bridge.h, whose calls it makes). CLAP's types are
    // clap-sys's, Oscairn's extensions' oscairn-clap-sys's (both vendored in core/clap-host/rust/vendor), so only what these
    // two headers declare is generated; the host's own functions (rust_clap_*, and the reference's) are not.
    let clap = format!("{root}/core/plugin-host/src/clap_host.h");
    let bridge = format!("{root}/core/clap-host/include/kick_clap/bridge.h");
    let own = [
        ("oscairn_clap_host", "crate::Host"),
        ("oscairn_clap_event", "crate::event::Event"),
        ("oscairn_clap_wake", "core::sync::atomic::AtomicU32"),
    ];
    let mut b = builder()
        .header(&clap)
        .allowlist_file(&clap)
        .allowlist_file(&bridge)
        .blocklist_function("(cpp|rust)_clap_.*")
        .blocklist_file(".*/clap-ext/include/.*")
        .blocklist_file(".*/third_party/clap/include/.*");
    for c in own.iter().map(|o| o.0) {
        b = b.blocklist_type(c);
    }
    let mut out = String::from("// Generated by bindgen 0.72.1 from core/plugin-host/src/clap_host.h by core/engine/rust/bindgen; regenerate after\n// changing it (the test clap_host_h_unchanged says when). Do not edit.\n");
    out += &allow.replace("dead_code,", "dead_code, unused_imports,");
    out += "use clap_sys::entry::clap_plugin_entry as clap_plugin_entry_t;\nuse clap_sys::events::clap_event_transport as clap_event_transport_t;\n";
    out += "use oscairn_clap_sys::{oscairn_asset_ref_t, oscairn_hardware_accelerator_t, oscairn_hardware_job_t, oscairn_hardware_lease_t, oscairn_hardware_request_t, oscairn_hardware_result_t, oscairn_sample_location_t};\n";
    out += "use oscairn_clap_sys::{oscairn_effect_resources_t, oscairn_memory_t, oscairn_sound_context_info_t, oscairn_sound_parameter_t};\n";
    out += "use oscairn_clap_sys::{oscairn_voice_budget_context_t, oscairn_voice_budget_note_t};\n";
    for (c, r) in own {
        out += &format!("pub type {c} = {r};\n");
    }
    out += &format!("pub const MADE_FROM: [u64; 2] = [{:#x}, {:#x}];\n", fnv(&clap), fnv(&bridge));
    out += &b.generate().expect("bindgen").to_string();
    std::fs::write(format!("{root}/core/clap-host/rust/src/bindings.rs"), out).expect("write");
}
