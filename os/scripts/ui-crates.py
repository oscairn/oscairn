#!/usr/bin/env python3
"""Writes the oscairn-ui-crates package's crate list (crates.inc) and hashes from ui/Cargo.lock:
every crate the lock names, which Buildroot downloads from crates.io at its download step and
checks against the lock's own checksum (the .crate file's SHA-256), so the device build runs cargo
offline (docs/rust-ui.md, "The device bundle"). Run it after Cargo.lock changes; it asks cargo for
the crates' licenses (cargo metadata, which may download what it lacks).

    ui-crates.py            write them
    ui-crates.py --check    say whether they match ui/Cargo.lock (the ui-crates test; no network)
"""
import json
import os
import re
import subprocess
import sys

repo = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..")
package = os.path.join(repo, "os", "buildroot", "package", "oscairn-ui-crates")
HASHES = os.path.join(package, "oscairn-ui-crates.hash")
CRATES = os.path.join(package, "crates.inc")


def locked():
    """(name, version, checksum) of each crates.io package in ui/Cargo.lock, in its order."""
    lock = open(os.path.join(repo, "ui", "Cargo.lock")).read()
    found = []
    for block in lock.split("[[package]]")[1:]:
        field = dict(re.findall(r'^(\w+) = "([^"]*)"$', block, re.M))
        if field.get("source", "").startswith("registry+https://github.com/rust-lang/crates.io-index"):
            found.append((field["name"], field["version"], field["checksum"]))
    return found


def hashes(crates):
    lines = ["# From ui/Cargo.lock's checksums (os/scripts/ui-crates.py): each crate file's SHA-256"]
    lines += [f"sha256  {c}  {n}-{v}.crate" for n, v, c in crates]
    return "\n".join(lines) + "\n"


def downloads(crates):
    lines = ["OSCAIRN_UI_CRATES_EXTRA_DOWNLOADS = \\"]
    lines += [f"\thttps://static.crates.io/crates/{n}/{n}-{v}.crate \\" for n, v, _ in crates]
    return "\n".join(lines).rstrip(" \\") + "\n"


def licenses():
    meta = json.loads(subprocess.check_output(["cargo", "metadata", "--locked", "--format-version", "1"], cwd=os.path.join(repo, "ui")))
    return sorted({p["license"] or "unknown" for p in meta["packages"] if (p.get("source") or "").startswith("registry+")})


crates = locked()
header = "# Generated by os/scripts/ui-crates.py from ui/Cargo.lock: run it again after the lock changes.\n"
if sys.argv[1:] == ["--check"]:
    have = open(CRATES).read()
    stale = [f for f, want in ((HASHES, hashes(crates)), (CRATES, downloads(crates))) if want not in open(f).read()]
    if stale or not have.startswith(header):
        sys.exit(f"stale for ui/Cargo.lock: {', '.join(stale) or CRATES}; run os/scripts/ui-crates.py")
    print(f"{len(crates)} crates, current")
else:
    open(HASHES, "w").write(hashes(crates))
    license_line = "OSCAIRN_UI_CRATES_LICENSE = " + ", ".join(licenses()) + " (each crate's own)\n"
    open(CRATES, "w").write(header + license_line + downloads(crates))
    print(f"{len(crates)} crates written")
